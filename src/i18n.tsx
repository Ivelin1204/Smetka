export type Lang = 'bg' | 'en'
const dicts: Record<Lang, Record<Key, string>> = { bg, en }

interface I18n {
  lang: Lang
  locale: string
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
  cat: (id: string) => string
}

const Ctx = createContext<I18n | null>(null)

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('smetka.lang')
    if (saved === 'bg' || saved === 'en') return saved
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('bg') ? 'bg' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const value = useMemo<I18n>(() => {
    const d = dicts[lang]
    const t = (key: Key, vars?: Record<string, string | number>) => {
      let s = d[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
      return s
    }
    return {
      lang,
      locale: lang === 'bg' ? 'bg-BG' : 'en-IE',
      setLang: (l) => {
        setLangState(l)
        document.documentElement.lang = l
        try {
          localStorage.setItem('smetka.lang', l)
        } catch {
          /* ignore */
        }
      },
      t,
      cat: (id) => (d[`cat.${id}` as Key] ?? id),
    }
  }, [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const v = useContext(Ctx)
  if (!v) throw new Error('I18nProvider missing')
  return v
}
